import { describe, expect, it } from 'vitest'
import { plexChoicesError, plexChoicesLoading, plexBrowseLoading, plexError, plexFollowFails, plexManyFilms, plexNotSetUp, plexUnreachable } from '../../src/mocks/handlers'
import { act, openApp, screen, waitFor, within } from '../utils/render'
import { mock, server } from '../utils/server'

describe('Plex', () => {
  it('lists a library with what is followed, and follows a film from it', async () => {
    const { user, router } = openApp('/admin/system')
    await user.click(await screen.findByRole('link', { name: /^Plex/ }))
    expect(router.state.location.pathname).toBe('/admin/plex')
    expect(await screen.findByText(/^Plex 1\.43\.5 has 2\sfilm and TV libraries\. Follow a show or a film below/)).toBeInTheDocument()
    const table = await screen.findByRole('grid', { name: 'Films, as Plex lists it' })
    expect(within(table).getAllByRole('row')).toHaveLength(5)
    expect(screen.getByText(/^4\stitles; 1 of the 4 shown is followed\.$/)).toBeInTheDocument()
    expect(within(table).getByText('Followed')).toBeInTheDocument()
    expect(within(table).queryByRole('button', { name: 'Follow Harbour Lights' })).not.toBeInTheDocument()
    await user.click(within(table).getByRole('button', { name: 'Follow Dark Harbour' }))
    expect(await screen.findByText('Added “Dark Harbour” to Films.')).toBeInTheDocument()
    expect(mock.plexFollowed).toContain('103')
    await waitFor(() => expect(within(screen.getByRole('grid', { name: 'Films, as Plex lists it' })).getAllByText('Followed')).toHaveLength(2))
  })

  it('narrows by genre, rating and title in the address, and follows the listing as a channel', async () => {
    const { user, router } = openApp('/admin/plex')
    await screen.findByRole('grid', { name: 'Films, as Plex lists it' })
    await user.selectOptions(screen.getByRole('combobox', { name: 'Genre' }), 'Animation')
    await user.selectOptions(await screen.findByRole('combobox', { name: 'Rating' }), 'gb/U')
    expect(router.state.location.search).toBe('?genre=1&rating=gb%2FU')
    await waitFor(() => expect(within(screen.getByRole('grid', { name: 'Films, as Plex lists it' })).getAllByRole('row')).toHaveLength(3))
    expect(screen.getByRole('textbox', { name: 'Channel name' })).toHaveAttribute('placeholder', 'Films: Animation, gb/U')
    await user.click(screen.getByRole('button', { name: 'Follow as a channel' }))
    expect(await screen.findByText('Following Films: Animation, gb/U. What it lists is being added.')).toBeInTheDocument()
    expect(mock.plexListings).toEqual([{ section: '1', params: { genre: '1', contentRating: 'gb/U' }, title: 'Films: Animation, gb/U' }])
    await user.type(screen.getByRole('textbox', { name: 'Title has' }), 'kite')
    await user.click(screen.getByRole('button', { name: 'Narrow' }))
    await waitFor(() => expect(within(screen.getByRole('grid', { name: 'Films, as Plex lists it' })).getAllByRole('row')).toHaveLength(2))
    await user.type(screen.getByRole('textbox', { name: 'Title has' }), 'zzz')
    await user.click(screen.getByRole('button', { name: 'Narrow' }))
    expect(await screen.findByText('Nothing matches')).toBeInTheDocument()
    await user.clear(screen.getByRole('textbox', { name: 'Title has' }))
    await user.click(screen.getByRole('button', { name: 'Narrow' }))
    await user.selectOptions(screen.getByRole('combobox', { name: 'Genre' }), 'Any genre')
    await user.selectOptions(screen.getByRole('combobox', { name: 'Rating' }), 'Any rating')
    expect(router.state.location.search).toBe('')
    await waitFor(() => expect(within(screen.getByRole('grid', { name: 'Films, as Plex lists it' })).getAllByRole('row')).toHaveLength(5))
  })

  it('keeps the title field with the address on Back', async () => {
    const { user, router } = openApp('/admin/plex')
    await screen.findByRole('grid', { name: 'Films, as Plex lists it' })
    const field = screen.getByRole('textbox', { name: 'Title has' })
    await user.type(field, 'kite'); await user.click(screen.getByRole('button', { name: 'Narrow' }))
    await user.clear(field); await user.type(field, 'boats'); await user.click(screen.getByRole('button', { name: 'Narrow' }))
    expect(router.state.location.search).toBe('?title=boats')
    await act(() => router.navigate(-1))
    await waitFor(() => expect(screen.getByRole('textbox', { name: 'Title has' })).toHaveValue('kite'))
  })

  it('says when the genres and ratings cannot be read, keeps a filter from the address, and reads them again', async () => {
    server.use(plexChoicesError)
    const { user } = openApp('/admin/plex?genre=7&rating=gb%2F18')
    expect(await screen.findByText(/^The genres could not be read:/)).toBeInTheDocument()
    expect(screen.getByText(/^The ratings could not be read:/)).toBeInTheDocument()
    expect(screen.getByRole('combobox', { name: /^Genre/ })).toBeDisabled()
    expect(screen.getByRole('combobox', { name: /^Genre/ })).toHaveDisplayValue('Genre 7')
    expect(screen.getByRole('combobox', { name: /^Rating/ })).toHaveDisplayValue('gb/18')
    server.resetHandlers()
    await user.click(screen.getByRole('button', { name: 'Read the filters again' }))
    await waitFor(() => expect(screen.getByRole('combobox', { name: /^Genre/ })).toBeEnabled())
    expect(screen.queryByRole('button', { name: 'Read the filters again' })).not.toBeInTheDocument()
  })

  it('says it is reading the filters', async () => {
    server.use(plexChoicesLoading)
    openApp('/admin/plex')
    expect(await screen.findByRole('option', { name: 'Reading genres…' })).toBeInTheDocument()
    expect(screen.getByRole('option', { name: 'Reading ratings…' })).toBeInTheDocument()
  })

  it('lists the TV library and follows a show with a name of its own', async () => {
    const { user } = openApp('/admin/plex?section=2')
    const table = await screen.findByRole('grid', { name: 'TV shows, as Plex lists it' })
    expect(within(table).getByText(/2018 · gb\/U · 154\sepisodes/)).toBeInTheDocument()
    await user.click(within(table).getByRole('button', { name: 'Follow Night Ferry' }))
    expect(await screen.findByText('Following Night Ferry. Its episodes are being added.')).toBeInTheDocument()
    await user.type(screen.getByRole('textbox', { name: 'Channel name' }), 'All TV')
    await user.click(screen.getByRole('button', { name: 'Follow as a channel' }))
    await waitFor(() => expect(mock.plexListings).toEqual([{ section: '2', params: {}, title: 'All TV' }]))
    await user.selectOptions(screen.getByRole('combobox', { name: 'Library' }), 'Films')
    expect(await screen.findByRole('grid', { name: 'Films, as Plex lists it' })).toBeInTheDocument()
  })

  it('pages through a long library', { timeout: 20_000 }, async () => {
    server.use(plexManyFilms)
    const { user, router } = openApp('/admin/plex')
    expect(await screen.findByText(/^1–50 of 120$/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Earlier' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Later' }))
    expect(router.state.location.search).toBe('?page=1')
    expect(await screen.findByText(/^51–100 of 120$/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Later' }))
    expect(await screen.findByText(/^101–120 of 120$/)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Later' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Earlier' }))
    expect(await screen.findByText(/^51–100 of 120$/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Earlier' }))
    expect(await screen.findByText(/^1–50 of 120$/)).toBeInTheDocument()
    expect(router.state.location.search).toBe('')
  })

  it('says what is wrong when Plex is not set up, does not answer, or refuses', async () => {
    server.use(plexNotSetUp)
    const a = openApp('/admin/plex')
    expect(await screen.findByText(/^Plex is not set up\. Put PLEX_URL/)).toBeInTheDocument()
    expect(screen.getByText('Plex cannot be read')).toBeInTheDocument()
    a.unmount()
    server.use(plexUnreachable)
    const b = openApp('/admin/plex')
    expect(await screen.findByText('Plex does not answer: Plex could not be reached: Connection refused.')).toBeInTheDocument()
    b.unmount()
    server.use(plexError)
    const c = openApp('/admin/plex')
    expect(await screen.findByRole('alert')).toBeInTheDocument()
    c.unmount()
  })

  it('says why following a film did not go through', async () => {
    server.use(plexFollowFails)
    const { user } = openApp('/admin/plex')
    const table = await screen.findByRole('grid', { name: 'Films, as Plex lists it' })
    await user.click(within(table).getByRole('button', { name: 'Follow Dark Harbour' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Plex refused the request (500).')
  })

  it('says why following did not go through', async () => {
    server.use(plexFollowFails, plexBrowseLoading)
    const { user } = openApp('/admin/plex')
    await user.click(await screen.findByRole('button', { name: 'Follow as a channel' }))
    expect(await screen.findAllByText('Plex refused the request (500).')).not.toHaveLength(0)
  })
})
